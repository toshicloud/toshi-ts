#!/usr/bin/env bash
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

# shellcheck source=/dev/null
source "$root/pin.env"

if ! command -v buf >/dev/null 2>&1; then
  echo "generate: buf is not on PATH; run it under mise (mise exec -- scripts/generate.sh)" >&2
  exit 1
fi

plugin="$root/node_modules/.bin/protoc-gen-es"
if [ ! -x "$plugin" ]; then
  echo "generate: $plugin is missing; run pnpm install --frozen-lockfile" >&2
  exit 1
fi

# The generator and the runtime it generates for are the same exact
# devDependency version in package.json, and both must be installed at it.
node --input-type=module - "$root" <<'NODE'
import { readFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
const names = ["@bufbuild/protoc-gen-es", "@bufbuild/protobuf"];

try {
  const read = (path) => JSON.parse(readFileSync(join(root, path), "utf8"));
  const dev = read("package.json").devDependencies ?? {};
  const pin = dev[names[0]];
  if (typeof pin !== "string" || !pin || names.some((name) => dev[name] !== pin)) {
    throw new Error("package.json must pin the generator and the runtime to the same exact version");
  }
  for (const name of names) {
    if (read(`node_modules/${name}/package.json`).version !== pin) {
      throw new Error(`${name} is not installed at the pinned version ${pin}`);
    }
  }
} catch (error) {
  console.error(`generate: ${error.message}; run pnpm install --frozen-lockfile`);
  process.exit(1);
}
NODE

buf generate "$TOSHI_API_REPOSITORY#commit=$TOSHI_API_REF" --path proto/toshi/workspace/v1 --path proto/toshi/github/v1 --path proto/toshi/permission.proto

# The contract constants are not a protoc plugin's output: the API repository
# writes them from the protos' bound options. Copy that file at the same commit.
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
git -C "$tmp" init -q
git -C "$tmp" fetch -q --depth 1 "$TOSHI_API_REPOSITORY" "$TOSHI_API_REF"
git -C "$tmp" show FETCH_HEAD:ts/gen/toshi/constants.ts >src/gen/toshi/constants.ts

# The package's version is the API's: VERSION at the same commit.
version="$(git -C "$tmp" show FETCH_HEAD:VERSION | tr -d '[:space:]')"
if ! [[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "generate: VERSION at $TOSHI_API_REF is not MAJOR.MINOR.PATCH" >&2
  exit 1
fi
cat >src/version.ts <<TS
// Code generated by scripts/generate.sh from the API's VERSION. DO NOT EDIT.

/**
 * The package version, the version of the Toshi API it is generated from;
 * test/node.test.ts keeps it equal to package.json.
 */
export const VERSION = "$version";
TS

# Every service of toshi.workspace.v1 the generated files declare, in one
# list the in-memory fake serves.
node --input-type=module - "$root" <<'NODE'
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const dir = join(process.argv[2], "src/gen/toshi/workspace/v1");
const byFile = new Map();
for (const file of readdirSync(dir).filter((name) => name.endsWith("_pb.ts")).sort()) {
  const names = [...readFileSync(join(dir, file), "utf8").matchAll(/^export const (\w+): GenService</gm)].map((match) => match[1]);
  if (names.length > 0) {
    byFile.set(file, names.sort());
  }
}
const all = [...byFile.values()].flat().sort();
if (all.length === 0) {
  console.error("generate: no service in src/gen/toshi/workspace/v1");
  process.exit(1);
}
const lines = [
  "// Code generated by scripts/generate.sh. DO NOT EDIT.",
  "// Every service the *_pb.ts files beside this one declare.",
  "",
  'import type { DescService } from "@bufbuild/protobuf";',
  ...[...byFile].map(([file, names]) => `import { ${names.join(", ")} } from "./${file.replace(/\.ts$/, ".js")}";`),
  "",
  "/** Every service of `toshi.workspace.v1`, ordered by name. */",
  "export const services: readonly DescService[] = [",
  ...all.map((name) => `  ${name},`),
  "];",
  "",
];
writeFileSync(join(dir, "services.ts"), lines.join("\n"));
NODE
